    <h1>Condicions d'ús i de reserva</h1>

    <h2>1. Reserves</h2>
    <ul>
        <li>Per fer qualsevol reserva cal estar registrat i tenir almenys un vehicle i un mètode de pagament.</li>
        <li>Una reserva garanteix una plaça al pàrquing escollit entre l'hora d'entrada i la de sortida indicades.
            La durada mínima és de 30 minuts i la màxima de 30 dies.</li>
        <li>El preu es calcula automàticament amb les tarifes vigents del pàrquing i s'hi afegeixen unes
            <strong>despeses de gestió del 10 %</strong>. L'import total es cobra en confirmar la reserva.</li>
        <li>Cada reserva té un número únic (format <code>CSJ-AAAAMMDD-XXXXXX</code>) i un justificant en PDF.</li>
    </ul>

    <h2>2. Entrada i sortida</h2>
    <ul>
        <li>El lector de matrícules reconeix el vehicle i obre la barrera. Es pot entrar fins a 30 minuts abans de l'hora reservada.</li>
        <li>Si se surt més tard de l'hora prevista (amb 5 minuts de cortesia), l'excés de temps es cobra automàticament
            amb el mateix mètode de pagament de la reserva, segons les tarifes vigents.</li>
    </ul>

    <h2>3. Cancel·lacions</h2>
    <ul>
        <li>Les reserves es poden cancel·lar des de «Les meves reserves» abans de l'hora d'entrada.</li>
        <li>En cancel·lar es reemborsa el preu de l'estada. Les despeses de gestió no són reemborsables.</li>
        <li>Les reserves no s'eliminen mai: es conserven com a cancel·lades per a l'historial.</li>
    </ul>

    <h2 id="privacitat">4. Privacitat i protecció de dades</h2>
    <ul>
        <li>Les dades personals es tracten d'acord amb el Reglament General de Protecció de Dades (RGPD) i la LOPDGDD,
            amb l'única finalitat de gestionar les reserves.</li>
        <li>El telèfon i el DNI es guarden <strong>xifrats</strong>. Les contrasenyes es guarden amb un resum (hash) no reversible.</li>
        <li>De les targetes només es guarden els 4 últims dígits: mai el número complet ni el CVV.</li>
        <li>Pots consultar i modificar les teves dades des del teu perfil.</li>
    </ul>
    <p class="ajuda">Projecte acadèmic: els pagaments són simulats i no es fa cap càrrec real.</p>
